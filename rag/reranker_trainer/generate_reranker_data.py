# 🔥 生成 reranker 微调三元组数据
# ==========================
def get_all_documents():
    """
    加载所有文档，转换为 LangChain Document 格式。
    """
    cache_path = f"{rag_config.VECTOR_STORE_DIR}/all_documents.json"

    if not os.path.exists(cache_path):
        raise FileNotFoundError(f"缓存文件不存在！请先运行 rag_pipeline.py\n路径：{cache_path}")

    with open(cache_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    return [
        Document(page_content=d["page_content"], metadata=d.get("metadata", {}))
        for d in data
    ]

def generate_reranker_data(queries, output_path):
    """
    生成 reranker 微调数据。

    参数:
    - queries: 预定义的查询列表
    - output_path: 输出 JSONL 文件路径，保存微调三元组（query, 正确文档, 难负例）
    """
    # 加载向量库和文档
    print("🔹 加载向量库和文档...")
    vs = load_vector_store(rag_config.VECTOR_STORE_DIR)
    all_docs = get_all_documents()

    # 创建检索器
    print("🔹 初始化混合检索器...")
    search_fn = create_hybrid_retriever(vectorstore=vs, all_documents=all_docs)

    # 保存微调三元组的列表
    training_data = []

    # 对每个 query 生成三元组数据
    for query in queries:
        print(f"\n正在处理查询: {query}")

        # 使用检索器召回 30 个相关的文档
        docs = search_fn(query=query, mode="hybrid", use_reranker=True)

        if len(docs) < 5:
            print(f"警告：查询 '{query}' 召回的文档少于 5 条，实际返回 {len(docs)} 条")
            continue

        # 取最相关的文档作为正例
        positive_doc = docs[0]  # 相关度最高的文档作为正例
        positive_page_content = positive_doc.page_content
        #如果最相关的文档score过低，也不适合作为正例
        if float(positive_doc.metadata.get("score")) < 0.15:
            print(f"警告：分数过低跳过该查询")
            continue

        # 选择相关度最高但 source 不同的文档作为负例
        negative_doc = None
        for doc in docs[1:]:  # 从第二条开始找
            if doc.metadata.get("source") != positive_doc.metadata.get("source"):
                negative_doc = doc
                break

        if negative_doc is None:
            print(f"警告：未能为查询 '{query}' 找到有效的难负例")
            continue

        negative_page_content = negative_doc.page_content

        # 构造三元组并保存
        training_data.append({
            "query": query,
            "positive_doc": positive_page_content,
            "negative_doc": negative_page_content
        })

    # 保存为 JSONL 格式
    print(f"\n🔹 保存数据到 {output_path}...")
    with open(output_path, "w", encoding="utf-8") as f:
        for entry in training_data:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")

    print(f"✅ 已生成 {len(training_data)} 条三元组数据，并保存至 {output_path}")


